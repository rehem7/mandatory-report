// 两难抉择：每题两条路都说得通，只有一条符合报告职责。
//
// 跟另外两个游戏的分工：
//   投放关考"该做什么"——可以试错，投错了当场告诉你为什么不能投；
//   找茬关考"谁说得不对"——错的人话里有个具体偏差，认出来就行；
//   两难关考"先做什么、按谁的话做"——场上没有人明显违规，两条路都是好心，
//   错在选择顺序和前提上（先通知家长还是先报、先帮扶还是先报、先问清还是先报）。
//
// 所以每题只有两个选项，而且两个选项的文字都要像"一个认真负责的人会做的决定"，
// 不能靠语气分辨。选完把另一条路的代价摊开：让人看见"另一个选择也是好心，
// 但代价落在这里"。选错可以换一条重选，但首答会被记下来。
//
// 两难不折算分数：每题只有两个选项，分数量表只有 0/33/67/100 四档，
// 错一道就掉到 67 分、一刀切到不达标，区分度还不如直接看"哪几道首答偏了"。
// 所以只记通关与薄弱知识点，跟找茬关一样 score 为 null。
const option = (id, text, { correct = false, outcome = "", note = "" } = {}) => ({ id, text, correct, outcome, note });
const dilemma = (id, title, setup, points, basis, options) => ({
  id, title, setup, basis,
  pointIndexes: Array.isArray(points) ? points : [points],
  options
});

