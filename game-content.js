// 普法游戏的内容配置。全部由后台提供，前端不写死任何关卡文案。
// 知识点用 materialId + pointIndex(es) 指回 content.js 的 materials[].points，
// 这样游戏里答错时能直接把"普法学习"里对应的那一条标红。
//
// 关于法条：法条是规则，不是可以"投进去"的动作。早先把法条做成卡片后，
// 同一栏里会同时出现「立即向公安机关报案」和「未保法第十一条：应当立即报告」，
// 说法重复，也容易让人以为要把法条当做法投进去。
// 现在法条只作为每个栏框的 basis，卡片区只剩具体处置。
//
// basis 的写法有两条硬规矩（tests/games.test.js 里有断言锁住）：
//   1. 必须写明出处再给条文：《未成年人保护法》（记作"未保法"）与九部门
//      《关于建立侵害未成年人案件强制报告制度的意见（试行）》（记作"九部门意见"），
//      写到"第几条第二款／第几项"。直接抄条文原文，不改写、不做概括——
//      被追问"依据是什么"时能当场翻到那一条对上。同一关的三栏依据互不重复，
//      免得学员翻一页又看到同一句。
//   2. 不写"本情形属于应当报告的情形"这类对当前栏框的裁定。防"照着抄"靠的是
//      展示时机，不是藏法条：栏框收齐、或投错需要解释时才展开，见 public/games.js 的 showBasis。
//
// 因为依据只在投完之后出现，抄原文不会提前泄露答案；反过来，学生看到的就是
// 真实条文，不是我们加工过的"教学版"，这一点对答辩很重要。
// 依据用到的条文：未保法第十一条第二款；九部门意见第二、四、六、七、十三、十四、十六条。

const card = (id, text, note, extra = {}) => ({ id, text, note, ...extra });

// points 可以是单个索引，也可以是数组：一个情形同时考几条知识点时用数组，
// 答错会把这几条一起在学习页标出来。
const bin = (id, title, scene, prompt, points, basis, correct, wrong) => ({
  id, title, scene, prompt, basis,
  pointIndex: Array.isArray(points) ? points[0] : points,
  pointIndexes: Array.isArray(points) ? points : [points],
  cards: [
    ...correct.map(([cardId, text], index) => card(cardId, text, "本情形适用的处置。", { correct: true, order: index })),
    ...wrong.map(([cardId, text, note]) => card(cardId, text, note, { correct: false }))
  ]
});

